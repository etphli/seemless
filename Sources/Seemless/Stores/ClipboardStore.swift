import AppKit
import CryptoKit
import Observation
import SeemlessCore

@MainActor @Observable
final class ClipboardStore {
    private(set) var entries: [ClipboardEntry] = []
    var error: String?
    private(set) var isMonitoring = false
    let root: URL
    let repository: HistoryRepository
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private var cleanupTimer: Timer?
    private var isCapturing = false
    var excludedApps: Set<String> = []

    init(root: URL, pasteboard: NSPasteboard = .general) {
        self.root = root
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
        repository = HistoryRepository(root: root)
    }

    func load() async {
        do {
            entries = try await repository.load()
            RuntimeLog.event(.clipboard, "History loaded: items=\(self.entries.count)")
        } catch {
            self.error = "Clipboard history could not be loaded: \(error.localizedDescription)"
            RuntimeLog.event(.clipboard, "History load failed", error: true)
        }
        cleanupTimer = Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { [weak self] _ in
            Task { @MainActor in await self?.refresh() }
        }
    }

    func setMonitoring(_ enabled: Bool) {
        timer?.invalidate()
        timer = nil
        isMonitoring = enabled
        RuntimeLog.event(.clipboard, "Recording: enabled=\(enabled)")
        lastChange = pasteboard.changeCount
        if enabled {
            timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
                Task { @MainActor in await self?.captureChange() }
            }
        }
    }

    func captureChange(sourceName: String? = nil, sourceBundleID: String? = nil) async {
        guard !isCapturing, pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            error = "Clipboard access is denied in System Settings. Allow access for Seemless to record copies."
            return
        }
        let source = NSWorkspace.shared.frontmostApplication
        let bundleID = sourceBundleID ?? source?.bundleIdentifier
        guard bundleID.map({ !excludedApps.contains($0) }) ?? true else { return }
        let ignored = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignored) else { return }
        let payload: ClipboardPayload
        let fingerprint: String
        var imageData: Data?
        if !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           let bitmap = NSBitmapImageRep(data: data), let png = bitmap.representation(using: .png, properties: [:]) {
            guard png.count <= HistoryPolicy.maximumImageBytes else {
                error = "An image larger than 20 MB was skipped."
                return
            }
            fingerprint = "image:" + SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            payload = .image(fileName: UUID().uuidString + ".png", width: bitmap.pixelsWide, height: bitmap.pixelsHigh)
            imageData = png
        } else if let text = pasteboard.string(forType: .string) ?? pasteboard.string(forType: .URL), !text.isEmpty {
            let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines))
            let isLink = ["https", "http", "mailto"].contains(url?.scheme?.lowercased() ?? "") && !text.contains("\n")
            payload = isLink ? .link(text) : .text(text)
            fingerprint = "text:" + SHA256.hash(data: Data(text.utf8)).map { String(format: "%02x", $0) }.joined()
        } else { return }
        isCapturing = true
        defer { isCapturing = false }
        let entry = ClipboardEntry(fingerprint: fingerprint, payload: payload, sourceName: sourceName ?? source?.localizedName ?? "Unknown app", sourceBundleID: bundleID)
        do { entries = try await repository.insert(entry, imageData: imageData); error = nil }
        catch {
            self.error = "Clipboard item could not be saved: \(error.localizedDescription)"
            RuntimeLog.event(.clipboard, "History write failed", error: true)
        }
    }

    func refresh() async {
        do { entries = try await repository.load() }
        catch { self.error = error.localizedDescription }
    }

    func togglePin(_ entry: ClipboardEntry) async {
        do { entries = try await repository.togglePin(entry.id) }
        catch { self.error = error.localizedDescription }
    }

    func remove(_ entry: ClipboardEntry) async {
        do { entries = try await repository.remove(entry.id) }
        catch { self.error = error.localizedDescription }
    }

    func clearUnpinned() async {
        do { entries = try await repository.clearUnpinned() }
        catch { self.error = error.localizedDescription }
    }

    func copy(_ entry: ClipboardEntry) async -> Bool {
        do {
            let image = try await repository.imageData(for: entry)
            if case .image = entry.payload, image == nil { throw HistoryError.invalidImage }
            pasteboard.clearContents()
            let succeeded: Bool
            if let image, let native = NSImage(data: image) { succeeded = pasteboard.writeObjects([native]) }
            else if let text = entry.payload.text { succeeded = pasteboard.setString(text, forType: .string) }
            else { succeeded = false }
            lastChange = pasteboard.changeCount
            if !succeeded { error = "The clipboard could not be updated." }
            return succeeded
        } catch {
            self.error = "This clipboard item could not be copied: \(error.localizedDescription)"
            return false
        }
    }

    func stop() { setMonitoring(false); cleanupTimer?.invalidate(); cleanupTimer = nil }
}
